static bool ParseByDelimiter(	unsigned int & dataPos, 
								const char * data, 
								unsigned int & dataLength, 
								char delimiter,
								CString & returnString)
{
	returnString = "";
	while(dataPos < dataLength)
	{
		if(data[dataPos] == delimiter)
		{
			dataPos++;
			return true;
		}
		returnString += data[dataPos];
		dataPos++;
	}
	if(returnString.GetLength() > 0)
		return true;
	return false;
}

template <typename T>
void SafeDelete(T *&pValue)
{
	if(pValue) 
	{
		delete pValue;
		pValue = NULL;
	}
}

template <typename T>
void SafeDeleteArray(T *&pValue)
{
	if(pValue) 
	{
		delete[] pValue;
		pValue = NULL;
	}
}

