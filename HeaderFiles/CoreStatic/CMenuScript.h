class CScriptLine
{
public:
	CScriptLine()
	{
		m_function				= -1;
		m_allocatedParamCount	= 0;
		m_strParams				= NULL;
		m_pPrevLine				= NULL;
		m_pNextLine				= NULL;
	}

	~CScriptLine()
	{
		DeleteMemory();
	}

	void DeleteMemory()
	{
		m_function = -1;
		m_allocatedParamCount = NULL;
		m_pPrevLine = NULL;
		m_pNextLine = NULL;
		if(m_strParams)
		{
			delete [] m_strParams;
			m_strParams = NULL;
		}
	}

    int GetIntByParam(int paramNum);
	CString GetStrByParam(int paramNum);
	float GetFloatByParam(int paramNum);

	int		  m_function;
	CString	 *m_strParams;
	int       m_allocatedParamCount;

	CScriptLine *m_pPrevLine;
	CScriptLine *m_pNextLine;
};

